"""Bake the small seamless architectural-detail array, in Blender or standalone Python.

Blender:
  blender -b --python scripts/maps/build-surface-swatches.py -- MAP_LIBRARY
Python:
  python scripts/maps/build-surface-swatches.py MAP_LIBRARY
"""
import argparse
import base64
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

# Order and indices must match the existing surfaceMaterialVersion 1 map packs.
# Only take the finish inside the metal panel: its frame belongs to that prop.
SOURCES = (
    ('de_nuke', 'hr_concrete_floor_001_color_psd_197daf44.png', (0, 0, 1, 1)),
    ('de_nuke', 'hr_metal_panel_001_color_psd_5bd8be4b.png', (.12, .12, .88, .88)),
    ('de_dust2', 'dust_kasbah_wood_planks_color_psd_9108b195.png', (0, 0, 1, 1)),
    ('de_anubis', 'hr_plaster_wall01_color_tga_7f224eae.png', (0, 0, 1, 1)),
    ('de_dust2', 'hr_dust_sand_02_color_psd_755e7eb9.png', (0, 0, 1, 1)),
    ('de_cache', 'brick_red_worn_003_color_psd_f57d3808.png', (0, 0, 1, 1)),
)
SIDE = 128


def luminance(path):
    try:
        import bpy
    except ImportError:
        from PIL import Image
        with Image.open(path) as image:
            rgb = np.asarray(image.convert('RGB'), dtype=np.float32)
    else:
        image = bpy.data.images.load(str(path), check_existing=False)
        try:
            image.colorspace_settings.name = 'Non-Color'
            width, height = image.size
            pixels = np.empty(width * height * 4, np.float32)
            image.pixels.foreach_get(pixels)
            rgb = np.rint(pixels.reshape(height, width, 4)[::-1, :, :3] * 255)
        finally:
            bpy.data.images.remove(image)
    return rgb @ np.array([.2126, .7152, .0722], dtype=np.float32)


def resample_axis(values):
    """Area filter across the first axis, including partial source pixels."""
    height, width = values.shape
    boundaries = np.linspace(0, height, SIDE + 1)
    indices = np.minimum(boundaries.astype(int), height - 1)
    integral = np.zeros((height + 1, width), np.float64)
    np.cumsum(values, axis=0, out=integral[1:])
    sampled = integral[indices] + (boundaries - indices)[:, None] * values[indices]
    return np.diff(sampled, axis=0) * (SIDE / height)


def soften_seam(tile):
    for axis in (tile, tile.T):
        for i in range(8):
            amount = (1 - i / 8) * .5
            delta = (axis[-i - 1] - axis[i]) * amount
            axis[i] += delta
            axis[-i - 1] -= delta


def sample_detail(image, crop, index):
    height, width = image.shape
    left, top, right, bottom = crop
    region = image[round(top * height):round(bottom * height), round(left * width):round(right * width)]
    tile = resample_axis(resample_axis(region).T).T
    soften_seam(tile)

    # Base colour, grime and outdoor shading are already baked into the mesh.
    # Use a periodic filter to isolate surface grain from that broad lighting.
    x = np.fft.rfftfreq(SIDE)
    y = np.fft.fftfreq(SIDE)
    radius2 = x[None, :] ** 2 + y[:, None] ** 2
    low_pass = np.exp(-2 * np.pi ** 2 * 0.70 ** 2 * radius2)
    broad_light = np.exp(-2 * np.pi ** 2 * 4.8 ** 2 * radius2)
    remove_broad = (0.84, 0.94, 0.66, 0.80, 0.75, 0.52)[index]
    result = np.fft.irfft2(np.fft.rfft2(tile) * low_pass * (1 - remove_broad * broad_light),
                           s=tile.shape, axes=(0, 1))
    result -= np.median(result)
    lo, hi = np.percentile(result, [3, 97])
    # Do not amplify paint grain or source compression on nearly flat metal.
    minimum_span = 2.3 if index == 1 else 1.5
    normalized = result / max(hi - lo, minimum_span)
    return np.clip(np.rint(7.5 + 13 * normalized), 0, 15).astype(np.uint8).ravel()


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('map_library', type=Path)
    parser.add_argument('--out', type=Path, default=Path('client/flat-surface-swatches.js'))
    args = parser.parse_args(argv)
    sources, payload = [], bytearray()
    for index, (map_id, name, crop) in enumerate(SOURCES):
        file, = (args.map_library / map_id).glob('*/raw/' + name)
        sources.append({'file': name, 'sha256': hashlib.sha256(file.read_bytes()).hexdigest(), 'crop': crop})
        levels = sample_detail(luminance(file), crop, index)
        payload.extend(((levels[::2] << 4) | levels[1::2]).tobytes())
    args.out.write_text('// Generated by scripts/maps/build-surface-swatches.py from Valve map albedo.\n'
                        + '// ' + json.dumps(sources, separators=(',', ':')) + '\n'
                        + 'export const side=' + str(SIDE) + ';\n'
                        + 'export const packed=' + json.dumps(base64.b64encode(payload).decode()) + ';\n', 'utf8')


if __name__ == '__main__':
    main(sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:])
