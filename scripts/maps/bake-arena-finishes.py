"""Author and bake the six architectural Graybox finishes. Geometry in game scenes is untouched.

blender -b -P scripts/maps/bake-arena-finishes.py -- artifacts/blender-arena/Surface-Library.blend
Use --source-blend to bake modified source groups from a previous library.
"""
import argparse
import base64
import gzip
import hashlib
import json
from pathlib import Path
import runpy
import sys

import bpy
import numpy as np

SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parents[1]
BASE = runpy.run_path(str(SCRIPTS / 'build-surface-swatches.py'))
SIDE = BASE['SIDE']
# Layer order is shared with the arena shader. World periods are metres.
RECIPES = [
    ('Enamel composite panel', 2.88, .54),
    ('Satin powder coat', 1.24, .31),
    ('Sealed ash cleat', 1.80, .33),
    ('Ceramic skim coat', 3.20, .35),
    ('Cast rubber paver', 2.40, .55),
    ('Mineral facing unit', 2.64, .43)
]

def tile(index):
    graph = BASE['FinishGraph'](RECIPES[index][0])
    calc, tone = graph.calc, graph.tone
    # Source lighting is flattened separately. These tiles carry only the wide,
    # flat planes and occasional narrow construction joint; no bump/highlight texture.
    def joint(uv, cycles, width, label, offset=0):
        phase = calc('FRACT', calc('MULTIPLY_ADD', uv, cycles, offset))
        distance = calc('MINIMUM', phase, calc('SUBTRACT', 1, phase))
        return calc('SUBTRACT', 1, graph.ramp(distance, width*.40, width, label))

    if index in (0, 4, 5):
        rows, columns = [(1, 1), (2, 2), (2, 1)][(0, 4, 5).index(index)]
        row = calc('FLOOR', calc('MULTIPLY', graph.v, rows))
        offset = calc('MULTIPLY', calc('MODULO', row, 2), .5) if index == 5 else 0
        u = joint(graph.u, columns, .005*columns, 'Vertical panel seam', offset)
        v = joint(graph.v, rows, .005*rows, 'Horizontal panel seam')
        value = tone(.50, (-.15, calc('MAXIMUM', u, v)))
    else:
        # A single, low-contrast joint separates broad steel, wood and plaster sheets.
        v = joint(graph.v, 1, .006, 'Sheet joint')
        value = tone(.50, (-.10, v))
    return graph.finish(value)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('library',type=Path)
    parser.add_argument('--source-blend',type=Path)
    parser.add_argument('--pack',type=Path,default=ROOT/'client/arena-finishes/shared.js')
    args = parser.parse_args(sys.argv[sys.argv.index('--')+1:])
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.context.preferences.filepaths.save_version=0
    if args.source_blend:
        with bpy.data.libraries.load(str(args.source_blend.resolve())) as (source, destination):
            destination.node_groups=['Finish / '+r[0] for r in RECIPES]
    scene = bpy.context.scene
    scene.render.engine = 'CYCLES'
    scene.cycles.samples = 1
    scene.render.bake.margin = 0
    layers=[]
    for index,(name,_,_) in enumerate(RECIPES):
        group = bpy.data.node_groups['Finish / '+name] if args.source_blend else tile(index)
        plane, img = BASE['sample_plane'](group,index)
        bpy.ops.object.bake(type='EMIT')
        pixels=np.empty(SIDE*SIDE*4,np.float32)
        img.pixels.foreach_get(pixels)
        detail=pixels.reshape(SIDE,SIDE,4)[:,:,0]
        if not np.all(np.isfinite(detail)) or np.ptp(detail)<.035:
            raise ValueError('Invalid bake '+name)
        level=np.rint(np.clip(detail-detail.mean()+.5,0,1)*63).astype(np.uint8)
        layers.append(level)
        mat=plane.data.materials[0]
        mat.node_tree.nodes.remove(mat.node_tree.nodes.active)
        bpy.data.images.remove(img)
        mat.asset_mark()
        plane.location=((index%3)*2.2,(1-index//3)*2.2,0)
    stack=np.stack(layers)
    delta=np.diff(stack,axis=2,prepend=np.zeros_like(stack[:,:,:1]))
    fields=dict(side=SIDE,finishes=RECIPES,sha256=hashlib.sha256(stack.tobytes()).hexdigest(),
                packed=base64.b64encode(gzip.compress(delta.tobytes(),compresslevel=9,mtime=0)).decode())
    args.pack.parent.mkdir(parents=True,exist_ok=True)
    args.pack.write_text('// Generated by scripts/maps/bake-arena-finishes.py\n' +
                         ''.join('export const '+k+'='+json.dumps(v,separators=(',',':'))+';\n' for k,v in fields.items()), 'utf8')
    scene.view_settings.view_transform='Standard'
    for screen in bpy.data.screens:
        for area in screen.areas:
            if area.type=='VIEW_3D':
                s=area.spaces.active
                s.shading.type='MATERIAL'
                s.overlay.show_overlays=False
                s.region_3d.view_distance=8.7
                s.region_3d.view_location=(2.2,1.1,0)
                s.region_3d.view_rotation=(1,0,0,0)
                s.region_3d.view_perspective='ORTHO'
    args.library.parent.mkdir(parents=True,exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=str(args.library.resolve()),compress=True)
    print('BAKED',len(layers),SIDE,'R8',fields['sha256'],flush=True)

if __name__=='__main__':
    main()
