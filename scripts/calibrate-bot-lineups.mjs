import fs from 'node:fs';
import {MAP} from '../shared/map-data.js';
import {initPhysics,raycastWorld,raycastWorldContact,floorHeight} from '../shared/physics.js';
import {GrenadeSimulation} from '../server/grenades.js';
import {simulateThrow,usefulThrow} from '../server/bot-trajectory.js';
fs.mkdirSync('artifacts/bot-rework',{recursive:true});
initPhysics(JSON.parse(fs.readFileSync('public/assets/map/collision.json','utf8')).positions);
const world=new GrenadeSimulation({raycastWorld,raycastContact:raycastWorldContact});
// World-space tactical targets, recalibrated against this project's collision
// and throw physics. Online CS2 setpos/setang values are not copied as lineups.
const point=(x,y,z)=>({x,y,z});
const definitions=[
 ['mid-cross','T','mid','*','smokegrenade',point(-11,0,-27),point(-8.1,-.7,-35.8)],
 ['a-ct','T','long','A','smokegrenade',point(39,.2,-48),point(30,.2,-57)],
 ['b-door','T','tunnels','B','smokegrenade',point(-42,.3,-55),point(-28,.3,-57)],
 ['b-window','T','tunnels','B','smokegrenade',point(-42,.3,-55),point(-35,.3,-67)],
 ['b-entry-flash','T','tunnels','B','flashbang',point(-42,.3,-52),point(-39,.3,-64)],
 ['a-car-fire','T','long','A','molotov',point(38,.2,-38),point(42,.4,-47)],
 ['ct-tunnel','CT','anchor-b','B','smokegrenade',point(-35,.3,-65),point(-43,.3,-58)],
 ['ct-short','CT','short','A','smokegrenade',point(22,2.5,-64),point(8,2.4,-53)],
 ['b-back-fire','T','tunnels','B','molotov',point(-42,.3,-57),point(-46,.8,-69)],
 ['b-back-he','T','tunnels','B','hegrenade',point(-42,.3,-57),point(-46,.8,-69)]
];
const results=[];
for(const [id,team,lane,site,weapon,near,target]of definitions){
 const ground=floorHeight(target.x,target.z,target.y+1.2,3);if(ground!==null)target.y=ground;
 const stands=MAP.nav.filter(n=>Math.abs(n.y-near.y)<1).sort((a,b)=>Math.hypot(a.x-near.x,a.z-near.z)-Math.hypot(b.x-near.x,b.z-near.z)).slice(0,4).map(n=>({...n,y:floorHeight(n.x,n.z,n.y+.2,1)??n.y}));
 let found=null,attempts=0;
 outer:for(const stand of stands){
 const yaw=Math.atan2(-(target.x-stand.x),-(target.z-stand.z));
 for(const strength of [1,.5,0])for(const delta of [0,.07,-.07,.16,-.16])for(let pitch=-.9;pitch<=1.25;pitch+=.07){
  attempts++;const input={yaw:yaw+delta,pitch,throwStrength:strength,throwMode:strength===1?'full':strength===.5?'lob':'drop'};
  const result=simulateThrow(world,{...stand,vx:0,vy:0,vz:0,crouch:false},weapon,input),spec={id,team,lane,site,weapon,stand:{x:stand.x,y:stand.y,z:stand.z},target,...input};
  if(usefulThrow(result,spec,world)){
   // Repeat with small positioning/angle errors: keep only forgiving throws.
   const offsets=[[-.1,0,.002],[.1,0,-.002],[0,.1,.002],[0,-.1,-.002]];
   if(!offsets.every(([x,z,a])=>usefulThrow(simulateThrow(world,{...stand,x:stand.x+x,z:stand.z+z},weapon,{...input,yaw:input.yaw+a}),spec,world)))continue;
   if(weapon==='smokegrenade'){for(let angle=0;angle<Math.PI;angle+=Math.PI/16){const dy=target.y+1.3,sight=[{x:target.x+Math.cos(angle)*6,y:dy,z:target.z+Math.sin(angle)*6},{x:target.x-Math.cos(angle)*6,y:dy,z:target.z-Math.sin(angle)*6}];if(world.clearSight(...sight)){spec.sight=sight;break;}}if(!spec.sight)continue;}
   found={...spec,expected:result};break outer;
  }
 }
 }
 console.log(JSON.stringify({id,attempts,found:!!found,stand:found?.stand,result:found&&{kind:found.expected.kind,point:found.expected.point}}),'');if(found)results.push(found);
}
fs.writeFileSync('server/bot-lineups.js','// Generated by scripts/calibrate-bot-lineups.mjs; validated in browser-game physics.\nexport const BOT_LINEUPS = '+JSON.stringify(results,null,2)+';\n');
fs.writeFileSync('artifacts/bot-rework/calibration.json',JSON.stringify({map:MAP.version,lineups:results},null,2));
if(results.length<6)process.exitCode=1;
